#!/usr/bin/env python3
"""Generate F2 wiring from the unchanged U280 wrapper ports/connectivity."""
import argparse
import re
from pathlib import Path
from f2_wrapper import generate_homgate

ROOT = Path(__file__).resolve().parents[2]
BANKS = list(range(13)) + list(range(20, 28))
# AXI request signals and widths on the AWS HBM side.
REQ = dict(araddr=34, arburst=2, arid=6, arlen=4, arsize=3, arvalid=1,
           awaddr=34, awburst=2, awid=6, awlen=4, awsize=3, awvalid=1,
           rready=1, bready=1, wdata=256, wlast=1, wstrb=32, wvalid=1)
RESP = dict(arready=1, awready=1, rdata=256, rid=6, rlast=1, rresp=2,
            rvalid=1, wready=1, bid=6, bresp=2, bvalid=1)

def ports(module):
    s = (ROOT / 'vitis/rtl' / f'{module}_top.v').read_text()
    s = s.split(');', 1)[0]
    return re.findall(r'(input|output)\s+wire\s*(\[[^\]]+\])?\s*(\w+)\s*[,\n]', s)

def inst(module, name, conns):
    return f'{module} {name} (\n' + ',\n'.join(f'  .{k}({v})' for k,v in conns.items()) + '\n);\n'

def stream_width(module, port):
    source = (ROOT/'vitis/rtl'/f'{module}_top.v').read_text()
    match = re.search(rf'parameter integer C_{port.upper()}_TDATA_WIDTH\s*=\s*(\d+)', source)
    if not match:
        raise ValueError(f'Missing stream width: {module}.{port}')
    return int(match[1])

def generate(out, hdk):
    config = (ROOT/'vitis/cfg/link_config.cfg').read_text()
    mapping = re.findall(r'sp=HomGate_1\.m(\d+)_axi:HBM\[(\d+)\]', config)
    if [(int(p),int(b)) for p,b in mapping] != list(enumerate(BANKS)):
        raise ValueError('HBM mapping changed; update the F2 host memory map before building')
    out.mkdir(parents=True, exist_ok=True)
    generate_homgate(ROOT/'vitis/rtl/HomGate_top.v',out/'HomGate_f2.sv')
    lines = ['// Generated by aws/scripts/generate.py. Do not edit.\n',
             'module cl_hoge (\n`include "cl_ports.vh"\n);\n',
             '`include "cl_id_defines.vh"\n',
             'wire clk = clk_main_a0;\nwire reset_n = rst_main_n & ~sh_cl_flr_assert;\nwire hbm_clk, hbm_locked, hbm_rst_n, core_rst_n, hbm_ready;\n',
             'hoge_hbm_clock HBM_CLOCK (.clk_in1(clk), .resetn(reset_n), .clk_out1(hbm_clk), .locked(hbm_locked));\n',
             'xpm_cdc_async_rst #(.RST_ACTIVE_HIGH(0), .DEST_SYNC_FF(4)) HBM_RESET (.src_arst(reset_n & hbm_locked), .dest_clk(hbm_clk), .dest_arst(hbm_rst_n));\n',
             'xpm_cdc_async_rst #(.RST_ACTIVE_HIGH(0), .DEST_SYNC_FF(4)) CORE_RESET (.src_arst(reset_n & hbm_ready), .dest_clk(clk), .dest_arst(core_rst_n));\n']
    # Shell outputs not used by the accelerator, following the HDK templates.
    for template in ['unused_pcim_template.inc', 'unused_cl_sda_template.inc', 'unused_apppf_irq_template.inc']:
        lines.append(f'`include "{template}"\n')
    lines += ['assign cl_sh_id0 = `CL_SH_ID0;\nassign cl_sh_id1 = `CL_SH_ID1;\n',
              "assign cl_sh_status0 = 32'h484f4745;\nassign cl_sh_status1 = {31'b0,hbm_ready};\nassign cl_sh_status2 = 0;\nassign cl_sh_status_vled = {15'b0,hbm_ready};\n",
              "reg [4:0] flr_count=0;\nalways @(posedge clk or negedge rst_main_n) begin\n  if (!rst_main_n) flr_count<=0;\n  else if (!sh_cl_flr_assert) flr_count<=0;\n  else if (!(&flr_count)) flr_count<=flr_count+1'b1;\nend\nassign cl_sh_flr_done = &flr_count;\nassign cl_sh_dma_rd_full = 0;\nassign cl_sh_dma_wr_full = 0;\nassign cl_sh_dma_pcis_ruser = 0;\nassign cl_sh_pcim_awcache=0; assign cl_sh_pcim_awlock=0; assign cl_sh_pcim_awprot=0; assign cl_sh_pcim_awqos=0; assign cl_sh_pcim_wid=0; assign cl_sh_pcim_wuser=0; assign cl_sh_pcim_arcache=0; assign cl_sh_pcim_arlock=0; assign cl_sh_pcim_arprot=0; assign cl_sh_pcim_arqos=0;\nassign tdo = 0;\n",
              "assign PCIE_EP_TXP=0; assign PCIE_EP_TXN=0; assign PCIE_RP_PERSTN=0; assign PCIE_RP_TXP=0; assign PCIE_RP_TXN=0;\n"]
    # Disabled DDR still needs the AWS physical pin tie-off module.
    template = (hdk/'cl/examples/CL_TEMPLATE/design/CL_TEMPLATE.sv').read_text()
    start = template.index('  sh_ddr')
    end = template.index('//=============================================================================', start)
    lines.append(template[start:end].replace('EN_DDR', '0').replace("cl_sh_ddr_stat_ack   = 'b0", "cl_sh_ddr_stat_ack   = 'b1"))
    for sig,w in (REQ|RESP).items():
        lines.append(f'wire [{w-1}:0] hbm_{sig} [0:31];\n')
    # Independently buffer all shell AXI channels using the same RTL elastic stage.
    # Payload widths are from the Small Shell interface and the existing converter.
    buses = {
        'PCIS': ('sh_cl_dma_pcis_', 'cl_sh_dma_pcis_', {
            'aw': [('awid',16),('awaddr',64),('awlen',8),('awsize',3),('awburst',2),('awcache',4),('awlock',1),('awprot',3),('awqos',4)],
            'w': [('wdata',512),('wstrb',64),('wlast',1)],
            'b': [('bid',16),('bresp',2)],
            'ar': [('arid',16),('araddr',64),('arlen',8),('arsize',3),('arburst',2),('arcache',4),('arlock',1),('arprot',3),('arqos',4)],
            'r': [('rid',16),('rdata',512),('rresp',2),('rlast',1)]}),
        'OCL': ('ocl_cl_', 'cl_ocl_', {
            'aw': [('awaddr',32)], 'w': [('wdata',32),('wstrb',4)],
            'b': [('bresp',2)], 'ar': [('araddr',32)],
            'r': [('rdata',32),('rresp',2)]})}
    shell_placement=[]
    resets=[]
    for bus,(shell_in,shell_out,channels) in buses.items():
        for ch,fields in channels.items():
            forward=ch in ['aw','w','ar']
            for sig,w in fields+[(ch+'valid',1),(ch+'ready',1)]:
                lines.append(f'wire [{w-1}:0] {bus.lower()}_{sig};\n')
            shell_payload='{'+','.join((shell_in if forward else shell_out)+s for s,_ in fields)+'}'
            local_payload='{'+','.join(bus.lower()+'_'+s for s,_ in fields)+'}'
            con={'clk':'clk','rst_n':'core_rst_n',
                 's_data':shell_payload if forward else local_payload,
                 'm_data':local_payload if forward else shell_payload,
                 's_valid':shell_in+ch+'valid' if forward else bus.lower()+'_'+ch+'valid',
                 's_ready':shell_out+ch+'ready' if forward else bus.lower()+'_'+ch+'ready',
                 'm_valid':bus.lower()+'_'+ch+'valid' if forward else shell_out+ch+'valid',
                 'm_ready':bus.lower()+'_'+ch+'ready' if forward else shell_in+ch+'ready'}
            stages=5 if bus=='PCIS' else 3
            name=f'{bus}_{ch.upper()}'
            shell_placement.append(f'{{{name} {stages} {int(forward)}}}')
            resets += [f'{name}/STAGE[{i}].RESET' for i in range(stages)]
            lines.append(inst(f'hoge_stream_pipeline #(.WIDTH({sum(w for _,w in fields)}), .STAGES({stages}))',name,con))
    # Stream widths, directions and FIFO depths stay derived from Vitis configuration.
    connections = {m:{} for m in ['HomGate','BRBack','BRFront']}
    placement=[]
    bk_placement=[]
    for idx,line in enumerate(config.splitlines()):
        if not line.startswith('stream_connect='): continue
        endpoints=line.split('=',1)[1].split(':')
        source, dest = [e.replace('_1.', '.') for e in endpoints[:2]]
        sm,sp=source.split('.'); dm,dp=dest.split('.')
        placement.append(f'{{{idx} {sm} {dm}}}')
        resets += [f'STREAM_{idx}/RESET']+[f'STREAM_PIPE_{idx}/STAGE[{i}].RESET' for i in range(3)]
        if sm=='HomGate' and sp in [f'axis{i:02d}' for i in range(2,10)]:
            mover=13+int(sp[-2:])-2
            bk_placement.append(f'{{{idx} {BANKS[mover]}}}')
        width=stream_width(sm,sp)
        if width != stream_width(dm,dp):
            raise ValueError(f'Stream width mismatch: {source} -> {dest}')
        depth=int(endpoints[2]) if len(endpoints)>2 else 32
        for prefix in ['s','q','m']:
            for sig,w in [('tdata',width),('tkeep',width//8),('tlast',1),('tvalid',1),('tready',1)]:
                lines.append(f'wire [{w-1}:0] stream{idx}_{prefix}_{sig};\n')
        for sig in ['tdata','tkeep','tlast','tvalid','tready']:
            connections[sm][sp+'_'+sig]=f'stream{idx}_s_{sig}'
            connections[dm][dp+'_'+sig]=f'stream{idx}_m_{sig}'
        con={'clk':'clk','rst_n':'core_rst_n'}
        for prefix in ['s','m']:
            net='s' if prefix=='s' else 'q'
            con.update({f'{prefix}_{s}':f'stream{idx}_{net}_{s}' for s in ['tdata','tkeep','tlast','tvalid','tready']})
        lines.append(inst(f'hoge_axis_fifo #(.WIDTH({width}), .DEPTH({depth}))',f'STREAM_{idx}',con))
        pipe={'clk':'clk','rst_n':'core_rst_n'}
        for port,net in [('s','q'),('m','m')]:
            pipe[port+'_data']='{'+','.join(f'stream{idx}_{net}_{s}' for s in ['tlast','tkeep','tdata'])+'}'
            pipe[port+'_valid']=f'stream{idx}_{net}_tvalid'
            pipe[port+'_ready']=f'stream{idx}_{net}_tready'
        lines.append(inst(f'hoge_stream_pipeline #(.WIDTH({width+width//8+1}), .STAGES(3))',f'STREAM_PIPE_{idx}',pipe))
        # These arithmetic producers cannot stop. Their capture FIFO must never fill.
        if (sm=='BRFront' and sp in [f'axis{i:02d}' for i in range(2,6)]) or (sm=='BRBack' and sp in ['axis04','axis05']):
            lines.append(f'// synthesis translate_off\nalways @(posedge clk) if (core_rst_n && stream{idx}_s_tvalid && !stream{idx}_s_tready) $fatal(1,"F2 stream overflow: {source}");\n// synthesis translate_on\n')
    for module in connections:
        reset=f'{module}_rst_n'
        lines.append(f'wire {reset};\n')
        lines.append(inst('hoge_local_reset',f'{module}_RESET',{'clk':'clk','arst_n':'core_rst_n','rst_n':reset}))
        resets.append(f'{module}_RESET')
        con=connections[module]
        for direction,width,p in ports(module):
            if p in con: continue
            if p=='ap_clk': con[p]='clk'
            elif p=='ap_rst_n': con[p]=reset
            elif p=='interrupt': con[p]=''
            elif p.startswith('s_axi_control_'):
                sig=p[len('s_axi_control_'):]
                con[p]='ocl_'+sig
                if sig in ['awaddr','araddr']: con[p]+='[11:0]'
            elif re.match(r'm\d+_axi_',p):
                index=int(p[1:3])
                signal=p.split('_axi_')[1]
                inactive=(index==0 and (signal.startswith('ar') or signal=='rready')) or (index>0 and (signal.startswith(('aw','w')) or signal=='bready'))
                if direction=='output' and inactive:
                    # Vitis handles the unused half of these directional ports.
                    # Keep the original wrapper unchanged and tie off at the adapter.
                    con[p]=''
                    continue
                w=width
                for match in re.findall(r'C_M\d+_AXI_(?:ADDR|DATA)_WIDTH',w):
                    w=w.replace(match,'64' if 'ADDR' in match else '512')
                lines.append(f'wire {w} {p};\n')
                con[p]=p
            else: raise ValueError(f'Unconnected {module}.{p}')
        lines.append(inst('HomGate_f2' if module=='HomGate' else module,module+'_1',con))
    # AWS supplies the converter: 512b AXI4/250MHz -> 256b AXI3/450MHz.
    wrapper = hdk/'common/ip/cl_ip/cl_ip.gen/sources_1/bd/cl_axi_sc_1x1/hdl/cl_axi_sc_1x1_wrapper.v'
    if not wrapper.is_file():
        raise RuntimeError('Missing AWS cl_axi_sc_1x1_wrapper.v; source hdk_setup.sh first')
    wp=wrapper.read_text()
    converter_ports=re.findall(r'^\s*(input|output)\s+(?:wire\s+)?(?:\[[^\]]+\]\s*)?(\w+)\s*;',wp,re.M)
    if not converter_ports: raise RuntimeError('Cannot parse AWS converter ports')
    for index,bank in enumerate(BANKS+[31]):
        host=index==21
        reset=f'converter{index}_rst_n'
        lines.append(f'wire {reset};\n')
        lines.append(inst('hoge_local_reset',f'CONVERTER_RESET_{index}',{'clk':'clk','arst_n':'core_rst_n','rst_n':reset}))
        resets.append(f'CONVERTER_RESET_{index}')
        con={'aclk_250':'clk','aresetn_250':reset,'aclk_450':'hbm_clk'}
        for direction,p in converter_ports:
            if p in con: continue
            bus,sig=p.split('_',1)
            if bus=='AXI3':
                unused=(not host and ((index==0 and sig.startswith(('ar','r'))) or (index>0 and sig.startswith(('aw','w','b')))))
                if unused:
                    con[p]="'0" if direction=='input' else ''
                    continue
                if sig in ['araddr','awaddr']:
                    lines.append(f'wire [63:0] conv{index}_{sig};\nassign hbm_{sig}[{bank}] = conv{index}_{sig}[33:0];\n')
                    con[p]=f'conv{index}_{sig}'
                elif sig in REQ|RESP: con[p]=f'hbm_{sig}[{bank}]'
                elif direction=='output': con[p]=''
                else: con[p]="'0"
            elif bus=='AXI4':
                if host:
                    con[p]='pcis_'+sig
                elif direction=='input' and ((index==0 and (sig.startswith('ar') or sig=='rready')) or (index>0 and (sig.startswith(('aw','w')) or sig=='bready'))):
                    con[p]="'0"
                elif sig in ['arcache','awcache']: con[p]="4'd1"
                elif sig in ['arburst','awburst']: con[p]="2'd1"
                elif sig in ['arsize','awsize']: con[p]="3'd6"
                elif sig in ['arid','awid','arlock','awlock','arprot','awprot','arqos','awqos']: con[p]="'0"
                elif sig in ['bid','rid','bresp','rresp']: con[p]=''
                else: con[p]=f'm{index:02d}_axi_{sig}'
            else: raise ValueError(p)
        lines.append(inst('cl_axi_sc_1x1_wrapper',f'HBM_CONVERTER_{index}',con))
        lines.append(f"assign hbm_arid[{bank}] = 0; assign hbm_awid[{bank}] = 0;\n")
        if not host:
            for sig in REQ:
                if sig in ['arid','awid']: continue
                if (index==0 and sig.startswith(('ar','r'))) or (index>0 and sig.startswith(('aw','w','b'))):
                    lines.append(f"assign hbm_{sig}[{bank}] = '0;\n")
    for bank in set(range(32))-set(BANKS+[31]):
        for sig in REQ: lines.append(f"assign hbm_{sig}[{bank}] = '0;\n")
    lines.append("cfg_bus_t hbm_stat();\nassign hbm_stat.addr=0; assign hbm_stat.wdata=0; assign hbm_stat.wr=0; assign hbm_stat.rd=0; assign hbm_stat.user=0;\n")
    con={'apb_clk':'clk_hbm_ref','i_clk_250m':'clk','i_rst_250m_n':'reset_n','i_clk_450m':'hbm_clk','i_rst_450m_n':'hbm_rst_n','hbm_stat_bus':'hbm_stat','o_hbm_ready':'hbm_ready','o_cl_sh_hbm_stat_int':''}
    con.update({('i_axi_' if s in REQ else 'o_axi_')+s:'hbm_'+s for s in REQ|RESP})
    for stack in [0,1]:
        for s in ['preset_n','paddr','pprot','psel','penable','pwrite','pwdata','pstrb','pready','prdata','pslverr']:
            p=f'hbm_apb_{s}_{stack}';con[('i_' if s=='preset_n' else 'o_')+p]=p
    lines.append(inst('cl_mem_hbm_wrapper #(.NUM_OF_AXI_PORTS(32))','HBM',con))
    lines.append('endmodule\n')
    (out/'cl_hoge.sv').write_text(''.join(lines))
    resets += [f'HomGate_1/DMA_RESET_{i}' for i in range(21)]
    for prefix, indices in [('DMA_CMD',range(21)),('DMA_READ',range(1,13)),('DMA_WRITE',[0]),('DMA_STATUS',[0])]:
        resets += [f'HomGate_1/{prefix}_{i}/STAGE[{stage}].RESET' for i in indices for stage in range(3)]
    resets += [f'HBM/PORT_RESET[{i}].LOCAL_RESET' for i in range(32)]
    resets += [f'HBM/READY_TREE/LEVEL{level}[{i}].NODE/RESET' for level,count in enumerate([8,4,2]) for i in range(count)]
    resets += ['HBM/READY_TREE/ROOT/RESET']
    (out/'physical_metadata.tcl').write_text('set hoge_shell_stages {\n'+'\n'.join(shell_placement)+'\n}\nset hoge_bk_fifos {'+' '.join(bk_placement)+'}\nset hoge_reset_instances {\n'+'\n'.join('{WRAPPER/CL/'+r+'}' for r in resets)+'\n}\n')
    (out/'stream_floorplan.tcl').write_text('set hoge_streams {\n'+'\n'.join(placement)+'\n}\n')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);p.add_argument('--hdk',type=Path,required=True)
    a=p.parse_args();generate(a.output,a.hdk)
